"""Generate formatted report tables from checked machine-readable evidence."""

import json
from pathlib import Path
from check_course_project import check

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results/course_project"


def main():
    check()
    primary = json.loads((OUT / "pa_results.json").read_text())["primary"]
    pa = []
    for seed, p, a in zip(
        (20261, 20262, 20263), primary["P_per_seed"], primary["A_per_seed"]
    ):
        pa.append(
            [
                str(seed),
                f"{p[0]:.6f}",
                f"{a[0]:.6f}",
                f"{p[1]*100:.4f}",
                f"{a[1]*100:.4f}",
            ]
        )
    p, a = primary["P_mean"], primary["A_mean"]
    pa.append(
        ["Mean", f"{p[0]:.6f}", f"{a[0]:.6f}", f"{p[1]*100:.4f}", f"{a[1]*100:.4f}"]
    )
    consensus = []
    for title, key, variant in [
        ("E11", "v1", "baseline"),
        ("Boundary v1", "v1", "corrected"),
        ("Polar v2", "v2", "v2"),
        ("Votes v3", "v3", "v3"),
        ("Energy v4", "v4", "full"),
    ]:
        metrics = json.loads((OUT / (key + ".json")).read_text())["metrics"]
        consensus.append(
            [
                title,
                f"{metrics['GED@30'][variant]:.6f}",
                f"{100*metrics['Dice_soft@30'][variant]:.3f}",
                f"{metrics['GED@50'][variant]:.6f}",
                f"{100*metrics['Dice_soft@50'][variant]:.3f}",
            ]
        )
    v4 = json.loads((OUT / "v4.json").read_text())["metrics"]
    ablation = []
    for title, key in [
        ("Full v4", "full"),
        ("Location only", "location"),
        ("No location", "no_location"),
        ("Original sample order", "no_order"),
        ("No energy readout", "no_energy"),
        ("Energy-only on v3", "energy_only"),
    ]:
        ablation.append(
            [
                title,
                f"{v4['GED@50'][key]:.6f}",
                f"{100*v4['Dice_soft@50'][key]:.3f}",
                f"{100*v4['Dice_mean'][key]:.3f}",
            ]
        )
    e = json.loads((OUT / "formal_e.json").read_text())
    preference = [
        [
            str(row["fold"]),
            str(row["patients"]),
            str(row["cases"]),
            f"{100*row['means']['e11']:.4f}",
            f"{100*row['means']['reference']:.4f}",
            f"{100*row['means']['candidate']:.4f}",
        ]
        for row in e["folds"]
    ]
    preference.append(
        [
            "Mean",
            "214",
            "1609",
            f"{100*e['means']['e11']:.4f}",
            f"{100*e['means']['reference']:.4f}",
            f"{100*e['means']['candidate']:.4f}",
        ]
    )
    tables = {
        "pa": pa,
        "consensus": consensus,
        "ablation": ablation,
        "preference": preference,
    }
    (OUT / "tables.json").write_text(json.dumps(tables, indent=2) + "\n")
    headers = {
        "pa": ["Seed", "P GED30", "A GED30", "P DS30 (%)", "A DS30 (%)"],
        "consensus": ["Method", "GED30", "DS30 (%)", "GED50", "DS50 (%)"],
        "ablation": ["Variant", "GED50", "DS50 (%)", "Preference Dice (%)"],
        "preference": ["Fold", "Patients", "Patches", "E11 (%)", "A (%)", "E (%)"],
    }
    lines = [
        "# Generated evidence tables",
        "",
        "Generated by scripts/render_course_tables.py; do not edit numbers manually.",
        "",
    ]
    for key, rows in tables.items():
        lines.extend(
            [
                "## " + key,
                "",
                "| " + " | ".join(headers[key]) + " |",
                "|" + "---|" * len(headers[key]),
            ]
        )
        lines.extend("| " + " | ".join(row) + " |" for row in rows)
        lines.append("")
    (OUT / "tables.md").write_text("\n".join(lines))
    print("TABLES_GENERATED: tables.json, tables.md")


if __name__ == "__main__":
    main()
